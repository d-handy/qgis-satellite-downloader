# Processing modes
MODE_COG = "cog"  # windowed read + clip via GDAL /vsicurl/
MODE_RAW = "raw"  # download whole asset files (swath products, netCDF)

# Asset keys of class, flag and quality bands. Interpolating these, or reading
# their averaged COG overviews, produces class values that do not exist. Kept
# narrow on purpose: a plain "data" asset is decided by its STAC metadata.
CATEGORICAL_ASSET = re.compile(
    r"(^|[_-])(scl|qa|qa_pixel|cmask|mask|classification|class|lccs_class|lulc|"
    r"landcover|burn[-_]?severity|flags?)($|[_-])",
    re.IGNORECASE,
)
_CLASSIFICATION_KEYS = ("classification:classes", "classification:bitfields")


def has_classification(asset_meta: dict | None) -> bool:
    """True if STAC asset metadata describes classes or bit fields."""
    if not asset_meta:
        return False
    if any(k in asset_meta for k in _CLASSIFICATION_KEYS):
        return True
    return any(
        any(k in band for k in _CLASSIFICATION_KEYS)
        for band in asset_meta.get("raster:bands") or []
        if isinstance(band, dict)
    )


@dataclass(frozen=True)
class Provider:
    key: str
    label: str
    stac_url: str
    signing: str | None = None  # "planetary-computer" or None
    supports_sort: bool = False  # STAC sort extension, per conformance classes
    # "GET" for APIs without POST search, "STATIC" for catalogues without API
    search_method: str = "POST"
    supports_query: bool = True  # "query" extension for server-side cloud filtering
    # (regex, replacement) applied to asset hrefs, e.g. public S3 buckets -> HTTPS
    href_rewrites: tuple[tuple[str, str], ...] = ()


@dataclass(frozen=True)
class MaskSpec:
    """How to tell clear from cloudy pixels in a quality band.

    ``kind="classes"``: ``invalid``/``cloudy``/``clear`` hold class values. If
    ``clear`` is given, every valid value outside it counts as cloudy.
    ``kind="bits"``: ``invalid``/``cloudy`` hold bit positions.
    """

    asset: str
    kind: str
    invalid: tuple[int, ...] = ()
    cloudy: tuple[int, ...] = ()
    clear: tuple[int, ...] = ()
    fill: int | None = None  # value of pixels without data, if not derivable


@dataclass(frozen=True)
class Collection:
    key: str
    label: str
    provider: str
    collection_id: str
    assets: tuple[str, ...]
    default_assets: tuple[str, ...]
    native_res: float  # metres
    mode: str = MODE_COG
    nodata: float | None = None
    has_cloud_cover: bool = True
    time_filter: bool = True  # False for static products such as DEMs
    note: str = ""
    # Nodata of assets whose files declare none and differ from ``nodata``
    asset_nodata: dict[str, float] = field(default_factory=dict)
    # Item properties that, besides the day, must match for scenes to share a
    # mosaic (e.g. ascending and descending Sentinel-1 passes stay apart).
    group_by: tuple[str, ...] = ()
    mask: MaskSpec | None = None
    # Common band names (STAC eo:common_name) -> asset key, so recipes can ask
    # for "red" regardless of the sensor.
    bands: dict[str, str] = field(default_factory=dict)
    category: str = "Optical"
    # Virtual asset key -> regex on real asset keys, for catalogues whose asset
    # keys are file names (swisstopo)
    asset_patterns: dict[str, str] = field(default_factory=dict)
    bbox: tuple[float, ...] | None = None  # spatial extent (W, S, E, N)
    interval: tuple[str | None, str | None] = (None, None)
    license: str | None = None
    # Class or flag bands whose key and metadata do not reveal it (e.g. "data")
    categorical_assets: tuple[str, ...] = ()

    def nodata_for(self, asset: str) -> float | None:
        return self.asset_nodata.get(asset, self.nodata)

    def is_categorical(self, asset: str, asset_meta: dict | None = None) -> bool:
        """Whether ``asset`` holds classes or flags rather than measured values.

        ``asset_meta`` is the asset's entry in a STAC item, whose
        ``classification:*`` fields settle it where the key does not.
        """
        return (
            (self.mask is not None and asset == self.mask.asset)
            or asset in self.categorical_assets
            or has_classification(asset_meta)
            or CATEGORICAL_ASSET.search(asset) is not None
        )

    def assets_for(self, names: tuple[str, ...] | list[str]) -> list[str] | None:
        """Asset keys for common band names, None if one is not offered."""
        try:
            return [self.bands[n] for n in names]
        except KeyError:
            return None


