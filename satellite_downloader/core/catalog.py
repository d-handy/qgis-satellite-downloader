"""Registration-free STAC sources and the collections the plugin offers.

Two layers:

- ``CURATED``: hand-checked entries (asset keys, native resolution, nodata the
  files actually carry, orbit grouping, mask band values). When a file declares
  no nodata (Sentinel-2 L2A), ``nodata`` supplies it so mosaics do not paint
  tile edges over valid pixels.
- ``data/collections.json``: generated by ``tools/build_catalog.py`` from the
  live catalogues, with anonymous access verified per collection. Curated
  entries win for the same provider and collection id.
"""

from __future__ import annotations

