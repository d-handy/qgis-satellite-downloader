GENERATED_FILE = Path(__file__).resolve().parent.parent / "data" / "collections.json"
STATIC_DIR = "static"  # next to GENERATED_FILE


def _interval(value) -> tuple[str | None, str | None]:
    """(start, end) from the catalogue JSON; either may be missing."""
    start, end = (list(value or []) + [None, None])[:2]
    return start, end


def _mask_from(data: dict | None) -> MaskSpec | None:
    if not data:
        return None
    return MaskSpec(
        asset=data["asset"],
        kind=data["kind"],
        invalid=tuple(data.get("invalid", ())),
        cloudy=tuple(data.get("cloudy", ())),
        clear=tuple(data.get("clear", ())),
        fill=data.get("fill"),
    )


def load_generated(path: Path = GENERATED_FILE) -> list[Collection]:
    """Collections from the generated catalogues; empty if the files are missing.

    ``path`` is the catalogue of the STAC APIs; the metadata of the static
    catalogues (``static/<provider>.json``) next to it is added.
    """
    files = [path] if path.exists() else []
    files += sorted((path.parent / STATIC_DIR).glob("*.json"))
    entries: list[dict] = []
    for file in files:
        entries += json.loads(file.read_text(encoding="utf-8")).get("collections", [])
    curated = {(c.provider, c.collection_id) for c in CURATED}
    out = []
    for e in entries:
        if (
            e["provider"] not in PROVIDERS
            or (e["provider"], e["collection_id"]) in curated
        ):
            continue
        out.append(
            Collection(
                key=e["key"],
                label=e["label"],
                provider=e["provider"],
                collection_id=e["collection_id"],
                assets=tuple(e["assets"]),
                default_assets=tuple(e["default_assets"]),
                native_res=float(e["native_res"]),
                mode=e["mode"],
                nodata=e.get("nodata"),
                has_cloud_cover=e.get("has_cloud_cover", False),
                time_filter=e.get("time_filter", True),
                note=e.get("note", ""),
                group_by=tuple(e.get("group_by", ())),
                mask=_mask_from(e.get("mask")),
                bands=dict(e.get("bands", {})),
                category=e.get("category", "Other"),
                asset_patterns=dict(e.get("asset_patterns", {})),
                bbox=tuple(e["bbox"]) if e.get("bbox") else None,
                interval=_interval(e.get("interval")),
                license=e.get("license"),
                categorical_assets=tuple(e.get("categorical_assets", ())),
            )
        )
    return out


